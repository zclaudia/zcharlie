"""``industry_peer_collect``: background collection task and batch management
(WP8 of the industry & peer reference plan).

One task collects the annual facts of a whole cohort roster for one report
period from one provider adapter (WP7's :class:`EastmoneyAnnualCollector`,
fake-injectable for tests), saves every company as a new immutable
:class:`~investment_agent.storage.models.peer.PeerAnnualSnapshot` version, and
then finalizes the batch exactly like the offline WP6 submission - freeze,
materialize evidence, build and save the three metric records, write the
``peer_batch_mapping/1`` artifact. The shared functions are reused
function-for-function from :mod:`investment_agent.industry_peers.batch`; the
collect job only adds the online collection and the checkpointing around it.

Discipline fixed by the technical design (§任务触发与失败处理):

* **Trusted payloads only.** :class:`PeerCollectPayload` is a new contract (the
  old ``FinancialSnapshotPayload`` semantics are never extended) generated by
  the trusted application alone (the management commands and the admission
  check below). The roster's tickers are resolved from the *saved* roster
  snapshot the payload is bound to (UUID + revision) - never from a
  model-supplied code list.
* **Dedup and generations.** The scope is
  ``(cohort_ref, report_period, provider, adapter_version)``; an existing
  ``queued``/``running`` run in the scope is reused instead of enqueuing a
  second one, and the ``(kind, idempotency_key)`` unique constraint blocks a
  concurrent duplicate. The idempotency key covers scope + generation over a
  canonical serialization; the generation derives from the highest finalized
  batch in the scope (mapping artifacts **and** prior runs, so a failed run
  never blocks the next explicit retry) plus one.
* **Checkpoints, not long transactions.** Companies are processed serially.
  Each company's fact write and its checkpoint (:meth:`record_metadata`, plus
  the artifact index under the run's ``research-runs`` directory) commit in one
  transaction, fenced by the claim's lease through the existing
  ``fence_writes`` machinery - a worker that lost its lease cannot write. A
  crashed attempt resumes from the checkpoint: finished companies are skipped,
  and the company that was mid-flight is served from the saved raw responses
  instead of re-sending its succeeded requests.
* **Frozen batch list.** The payload binds the roster revision at enqueue
  time, so a roster change mid-task never enters this batch; the finalize
  freezes every member's input version once (this run's new version, the
  allowed reuse of the member's older in-scope version, or an explicit gap)
  and the computation never consults "current latest" per item again.
* **Failures.** One company's failure (unknown company type, terminal or data
  error - never blindly retried here, WP7 owns the retry budget for transient
  transport errors) neither succeeds the group nor fails it: the mapping ends
  ``partial`` with the per-company reason in the manifest and the run
  metadata. Transient transport failures propagate, so the worker's existing
  limited retry requeues the run; the checkpoint makes the retry resume.

Raw artifacts (request records, response hashes and the response bodies the
resume cache reads) live under the existing research-runs data directory next
to the WP6 mapping artifact::

    {data_dir}/research-runs/{run_id}/peer-collect/{index,responses/}
    {data_dir}/research-runs/{run_id}/peer-batch-mapping.json

The run's ``metadata_json`` carries the checkpoint summary, the artifact paths
and the submitted mapping hash. GET endpoints and the agent never enqueue this
job: only :func:`enqueue_peer_collect` (management commands and the admission
check) creates runs.
"""

