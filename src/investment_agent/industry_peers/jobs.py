def request_identity(operation: str, params: Mapping[str, str]) -> str:
    """sha256 over the canonical planned request (the response-cache key)."""

    body = {"operation": operation, "params": {key: params[key] for key in sorted(params)}}
    canonical = json.dumps(body, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _operation_of_url(url: str) -> str | None:
    return _URL_OPERATIONS.get(urlsplit(url).path)


def _atomic_write(path: Path, payload: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    try:
        tmp.write_text(payload, encoding="utf-8")
        os.replace(tmp, path)
    finally:
        if tmp.exists():
            tmp.unlink()


class CollectArtifactStore:
    """The run's raw collection artifacts under ``research-runs/<run_id>``.

    The request index (per-company status, references and request records) is
    the checkpoint the resume reads; the response bodies keyed by the canonical
    planned request power the WP7 reuse check, so a resumed attempt never
    re-sends an already-succeeded request.
    """

    def __init__(self, data_dir: Path, run_id: int) -> None:
        self.root = Path(data_dir) / "research-runs" / str(run_id) / COLLECT_DIRNAME
        self._responses_dir = self.root / RESPONSES_DIRNAME
        self._responses_index_path = self._responses_dir / RESPONSES_INDEX_FILENAME

    @property
    def index_path(self) -> Path:
        return self.root / INDEX_FILENAME

    @property
    def responses_index_path(self) -> Path:
        return self._responses_index_path

    def load_index(self) -> dict[str, Any]:
        if not self.index_path.is_file():
            return {}
        try:
            data = json.loads(self.index_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            return {}
        return data if isinstance(data, dict) else {}

    def save_index(self, index: Mapping[str, Any]) -> None:
        _atomic_write(
            self.index_path,
            json.dumps(index, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        )

    def _responses_index(self) -> dict[str, Any]:
        if not self._responses_index_path.is_file():
            return {}
        try:
            data = json.loads(self._responses_index_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError):
            return {}
        return data if isinstance(data, dict) else {}

    def save_response(self, operation: str, params: Mapping[str, str], body: bytes) -> str:
        """Save one 200 answer; returns its sha256 (recorded in the index)."""

        key = request_identity(operation, params)
        digest = hashlib.sha256(body).hexdigest()
        self._responses_dir.mkdir(parents=True, exist_ok=True)
        target = self._responses_dir / f"{key}.body"
        tmp = target.with_name(f"{target.name}.{os.getpid()}.tmp")
        try:
            tmp.write_bytes(body)
            os.replace(tmp, target)
        finally:
            if tmp.exists():
                tmp.unlink()
        responses = self._responses_index()
        responses[key] = {
            "operation": operation,
            "params": {name: params[name] for name in sorted(params)},
            "sha256": digest,
            "bytes": len(body),
        }
        _atomic_write(
            self._responses_index_path,
            json.dumps(responses, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        )
        return digest

    def load_response(self, operation: str, params: Mapping[str, str]) -> bytes | None:
        """The saved answer for this exact planned request, hash-verified."""

        key = request_identity(operation, params)
        meta = self._responses_index().get(key)
        if not isinstance(meta, dict):
            return None
        path = self._responses_dir / f"{key}.body"
        if not path.is_file():
            return None
        try:
            body = path.read_bytes()
        except OSError:
            return None
        if hashlib.sha256(body).hexdigest() != meta.get("sha256"):
            return None  # a mutated body is refetched, never parsed
        return body


class SavedResponseCache:
    """WP7 ``AnnualResponseCache`` over the run's saved raw responses."""

    def __init__(self, store: CollectArtifactStore) -> None:
        self._store = store

    def saved_response(self, operation: str, params: Mapping[str, str]) -> bytes | None:
        return self._store.load_response(operation, params)


class ArtifactSavingSource:
    """Transport wrapper that archives every 200 answer into the run's artifacts.

    Saving at the transport level captures each answer exactly once (retries
    overwrite the same request key), independent of the parse outcome, so the
    checkpoint's request records always reference a stored body.
    """

    def __init__(self, inner: EastmoneyAnnualSource, store: CollectArtifactStore) -> None:
        self._inner = inner
        self._store = store

    async def fetch(self, url: str, params: Mapping[str, str]) -> RawAnnualResponse:
        response = await self._inner.fetch(url, params)
        operation = _operation_of_url(url)
        if response.status == 200 and operation is not None:
            self._store.save_response(operation, params, response.body)
        return response


