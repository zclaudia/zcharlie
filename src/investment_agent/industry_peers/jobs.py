def _period_for(kind: str, period_end: date) -> Period:
    """Flows cover Jan 1 - Dec 31; stocks are the Dec 31 point; ROE the
    disclosed full-year ratio - identical to the WP3 importer's rule."""

    if kind == "flow":
        return Period(start=date(period_end.year, 1, 1), end=period_end, basis="period_to_date/annual")
    if kind == "stock":
        return Period(start=period_end, end=period_end, basis="point_in_time")
    return Period(start=date(period_end.year, 1, 1), end=period_end, basis="annual_ratio")


def build_snapshot_fields(
    collection: CompanyAnnualCollection,
) -> tuple[dict[str, PeerAnnualField], dict[str, dict[str, Any]]]:
    """The WP3-shaped field entries and per-field proofs of one collection.

    ``NOTICE_DATE`` / ``UPDATE_DATE`` travel from the source rows into
    ``disclosed_on`` / ``updated_on``, so the online facts carry the
    version-notice date WP4 needs for materialization (approximate day
    precision is applied there, never here). The ROE percent value was
    divided by 100 exactly once by the WP7 adapter; the raw percent stays in
    ``raw_value``. Nothing is invented: fields without an original-document
    check stay ``candidate`` with explicit ``None`` proof slots.
    """

    fields: dict[str, PeerAnnualField] = {}
    proofs: dict[str, dict[str, Any]] = {}
    for spec in ANNUAL_METRICS:
        annual_field = collection.fields[spec.metric]
        row = collection.source_rows.get(spec.source_table)
        kind = _PERIOD_KINDS.get(spec.metric)
        if kind is None:
            raise ValueError(
                f"the adapter reports metric {spec.metric!r} without a WP8 period kind"
            )
        if annual_field.value is None and annual_field.missing_reason is None:
            raise ValueError(
                f"adapter returned {spec.metric!r} without value and without missing_reason"
            )
        fields[spec.metric] = PeerAnnualField(
            metric=spec.metric,
            value=annual_field.value,
            unit=annual_field.unit,
            currency=annual_field.currency,
            period=_period_for(kind, collection.report_period),
            source_field=annual_field.source_field,
            raw_value=annual_field.raw_value,
            raw_unit=annual_field.raw_unit,
            disclosed_on=row.notice_date if row is not None else None,
            updated_on=row.update_date if row is not None else None,
            acquired_at=collection.captured_at,
            verification=PeerFieldVerification.CANDIDATE,
            missing_reason=annual_field.missing_reason,
        )
        proofs[spec.metric] = {
            "metric": spec.metric,
            "status": "candidate",
            "original_ref": None,
            "pdf_hash": None,
            "report_identity": None,
            "pdf_page": None,
            "header": None,
            "raw_value": annual_field.raw_value,
            "raw_unit": annual_field.raw_unit,
            "parsed_value": (
                str(annual_field.value) if annual_field.value is not None else None
            ),
            "period": collection.report_period.isoformat(),
            "accounting_scope": None,
            "locator_excerpt": None,
            "locator_excerpt_sha256": None,
            "checked_at": None,
            "checked_by": None,
            "check_rule_version": None,
            "audit_record": None,
            "source_response_sha256": annual_field.response_hash,
            "source_notice_date": (
                row.notice_date.isoformat() if row is not None and row.notice_date else None
            ),
            "source_update_date": (
                row.update_date.isoformat() if row is not None and row.update_date else None
            ),
            "company_type": collection.company_type,
            "note": (
                "collected from the provider API by the online adapter; no "
                "original-document check exists in the first phase"
            ),
        }
    return fields, proofs


def snapshot_hashes(
    fields: Mapping[str, PeerAnnualField], proofs: Mapping[str, dict[str, Any]]
) -> tuple[str, str]:
    """sha256 over the WP3 canonical semantic serialization.

    Covers amounts, semantics, the source revision marks and proofs; excludes
    ``acquired_at`` and every local path, so a re-collection of identical
    content lands on the existing unique key instead of appending a version.
    The collection stores no retry times or local paths in the row, so both
    hashes agree (the WP3 importer's convention).
    """

    payload = {
        "schema": SEMANTIC_HASH_SCHEMA,
        "fields": {
            metric: {
                key: value
                for key, value in entry.model_dump(mode="json").items()
                if key != "acquired_at"
            }
            for metric, entry in fields.items()
        },
        "verification": dict(proofs),
    }
    canonical = canonical_json(payload)
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return digest, digest


