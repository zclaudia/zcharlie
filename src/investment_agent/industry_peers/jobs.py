class PeerCollectPayload(BaseModel):
    """One roster-year collection request.

    Every field is fixed by the trusted application at enqueue time: the
    roster is bound by snapshot UUID + revision (the tickers are resolved from
    that saved snapshot, never carried in the payload), and ``generation`` is
    derived from the finalized batches of the scope. Two runs of one scope
    differ by generation; the collection mode travels for audit (both modes
    walk the whole roster in the first phase).
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    cohort_snapshot_id: str = Field(pattern=r"^[0-9a-f]{32}$|^[0-9a-f-]{36}$")
    cohort_revision: int = Field(ge=1)
    report_period: date
    provider: str = Field(min_length=1, max_length=64)
    adapter_version: str = Field(min_length=1, max_length=64)
    mode: CollectMode = "full"
    generation: int = Field(ge=1)

    @field_validator("report_period")
    @classmethod
    def _annual_period(cls, value: date) -> date:
        if (value.month, value.day) != (12, 31):
            raise ValueError(
                f"peer collection collects annual reports; report_period must end in "
                f"12-31, got {value.isoformat()}"
            )
        return value

    def cohort_ref(self) -> ObjectRef:
        return ObjectRef(
            kind="peer_cohort_snapshot",
            id=uuid.UUID(self.cohort_snapshot_id),
            revision=self.cohort_revision,
        )


def peer_collect_idempotency_key(payload: PeerCollectPayload) -> str:
    """Canonical scope + generation digest (the ``(kind, key)`` uniqueness).

    The readable generation keeps queued runs distinguishable at a glance; the
    digest covers the full scope canonically, so the same scope+generation
    always yields the same key and a different payload under it is rejected as
    an idempotency mismatch instead of silently reusing the run.
    """

    body = {
        "cohort_snapshot_id": payload.cohort_snapshot_id,
        "cohort_revision": payload.cohort_revision,
        "report_period": payload.report_period.isoformat(),
        "provider": payload.provider,
        "adapter_version": payload.adapter_version,
        "generation": payload.generation,
    }
    canonical = json.dumps(body, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    return f"{PEER_COLLECT_KIND}:g{payload.generation}:{digest}"


def payload_of(run: PipelineRun) -> PeerCollectPayload | None:
    """The validated payload of a collect run, or ``None`` for foreign rows."""

    if run.kind != PEER_COLLECT_KIND:
        return None
    try:
        return PeerCollectPayload.model_validate(run.request_json)
    except ValueError:
        return None


