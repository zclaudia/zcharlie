@dataclass(frozen=True)
class PeerCollectEnqueueResult:
    """Outcome of one trusted enqueue attempt."""

    run: PipelineRun
    payload: PeerCollectPayload
    created: bool
    scope_reused: bool
    """An already queued/running run of the scope was reused."""
    generation: int


async def find_active_scope_run(
    session: AsyncSession,
    *,
    cohort: PeerCohortSnapshot,
    report_period: date,
    provider: str,
    adapter_version: str,
) -> PipelineRun | None:
    """A queued/running collect run of the scope, oldest first.

    The dedup scope is ``(cohort_ref, period, provider, adapter_version)``:
    generations inside one scope never run in parallel, so a refresh reuses
    the active task instead of enqueueing a second one.
    """

    rows = list(
        (
            await session.execute(
                select(PipelineRun)
                .where(
                    PipelineRun.kind == PEER_COLLECT_KIND,
                    PipelineRun.status.in_(ACTIVE_STATUSES),
                )
                .order_by(PipelineRun.id.asc())
            )
        ).scalars()
    )
    for row in rows:
        payload = payload_of(row)
        if payload is None:
            continue
        if (
            payload.cohort_snapshot_id == cohort.id
            and payload.cohort_revision == cohort.revision
            and payload.report_period == report_period
            and payload.provider == provider
            and payload.adapter_version == adapter_version
        ):
            return row
    return None


async def _runs_in_scope(
    session: AsyncSession,
    *,
    cohort: PeerCohortSnapshot,
    report_period: date,
    provider: str,
    adapter_version: str,
) -> list[PipelineRun]:
    rows = list(
        (
            await session.execute(
                select(PipelineRun)
                .where(PipelineRun.kind == PEER_COLLECT_KIND)
                .order_by(PipelineRun.id.asc())
            )
        ).scalars()
    )
    found = []
    for row in rows:
        payload = payload_of(row)
        if payload is None:
            continue
        if (
            payload.cohort_snapshot_id == cohort.id
            and payload.cohort_revision == cohort.revision
            and payload.report_period == report_period
            and payload.provider == provider
            and payload.adapter_version == adapter_version
        ):
            found.append(row)
    return found


async def enqueue_peer_collect(
    session: AsyncSession,
    *,
    report_period: date,
    mode: CollectMode,
    triggered_by: str,
    data_dir: Path,
    cohort_key: str | None = None,
    cohort_row: PeerCohortSnapshot | None = None,
    provider: str = PROVIDER,
    adapter_version: str = ADAPTER_VERSION,
    generation: int | None = None,
    max_attempts: int = 3,
) -> PeerCollectEnqueueResult:
    """Trusted admission to the collect queue (management commands, admission).

    Resolves the roster (an explicit row, else the latest revision of
    ``cohort_key`` - a missing roster raises with the import-roster hint),
    reuses an active run of the scope, derives the next generation from the
    finalized batches (mapping artifacts *and* prior runs of the scope, so a
    failed run cannot pin the key) and enqueues under the
    ``(kind, idempotency_key)`` unique constraint, which absorbs a concurrent
    duplicate into the winning row.
    """

    if cohort_row is None:
        if cohort_key is None:
            raise ValueError("enqueue_peer_collect needs cohort_row or cohort_key")
        from investment_agent.storage.repositories.peer import PeerCohortSnapshotRepository

        cohort_row = await PeerCohortSnapshotRepository(session).latest(cohort_key=cohort_key)
    if cohort_row is None:
        raise ValueError(
            "no cohort roster saved"
            + (f" under cohort_key={cohort_key!r}" if cohort_key else "")
            + "; run `ia peers import-roster` first"
        )

    pack = cohort_metric_pack(cohort_row.payload)
    if pack != BAIJIU_PACK:
        raise ValueError(
            f"online peer collection does not support metric pack {pack}; "
            "bank annual fields remain offline/candidate until the adapter is extended"
        )

    active = await find_active_scope_run(
        session,
        cohort=cohort_row,
        report_period=report_period,
        provider=provider,
        adapter_version=adapter_version,
    )
    if active is not None:
        active_payload = payload_of(active)
        if active_payload is None:  # pragma: no cover - validated at enqueue
            raise ValueError(f"active collect run {active.id} has an unreadable payload")
        return PeerCollectEnqueueResult(
            run=active,
            payload=active_payload,
            created=False,
            scope_reused=True,
            generation=active_payload.generation,
        )

    scan = await scan_committed_batch_mappings(session, data_dir)
    scope_mappings = mappings_in_scope(
        scan.valid,
        cohort_ref=ObjectRef(
            kind="peer_cohort_snapshot", id=uuid.UUID(cohort_row.id), revision=cohort_row.revision
        ),
        report_period=report_period,
        provider=provider,
        adapter_version=adapter_version,
    )
    prior_runs = await _runs_in_scope(
        session,
        cohort=cohort_row,
        report_period=report_period,
        provider=provider,
        adapter_version=adapter_version,
    )
    prior_generations = [
        payload.generation
        for payload in (payload_of(run) for run in prior_runs)
        if payload is not None
    ]
    derived = max(next_generation(scope_mappings), max(prior_generations, default=0) + 1)
    payload = PeerCollectPayload(
        cohort_snapshot_id=cohort_row.id,
        cohort_revision=cohort_row.revision,
        report_period=report_period,
        provider=provider,
        adapter_version=adapter_version,
        mode=mode,
        generation=generation if generation is not None else derived,
    )
    run, created = await PipelineRunRepository(session).enqueue(
        kind=PEER_COLLECT_KIND,
        idempotency_key=peer_collect_idempotency_key(payload),
        triggered_by=triggered_by,
        request_json=payload.model_dump(mode="json"),
        max_attempts=max_attempts,
    )
    return PeerCollectEnqueueResult(
        run=run,
        payload=payload,
        created=created,
        scope_reused=False,
        generation=payload.generation,
    )


