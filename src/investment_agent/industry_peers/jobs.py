class _HandlerError(RuntimeError):
    """Terminal payload/roster damage: the run fails, retries cannot fix it."""


class PeerCollectHandler(BaseJobHandler):
    """Executes one ``industry_peer_collect`` run (see the module docstring)."""

    kind = PEER_COLLECT_KIND

    def __init__(
        self,
        *,
        settings: Settings,
        source: EastmoneyAnnualSource | None = None,
        retry_backoff_seconds: float = 1.0,
        sleep: Any = asyncio.sleep,
    ) -> None:
        self.settings = settings
        self._injected_source = source
        self._retry_backoff_seconds = retry_backoff_seconds
        self._sleep = sleep

    # -- execution ---------------------------------------------------------- #

    async def execute(self, job: ClaimedJob, ctx: JobContext) -> JobOutcome:
        payload = PeerCollectPayload.model_validate(job.request_json)
        async with session_scope() as session:
            cohort_row = await session.get(PeerCohortSnapshot, payload.cohort_snapshot_id)
            if cohort_row is None or cohort_row.revision != payload.cohort_revision:
                raise _HandlerError("the online collection roster version is unavailable")
            pack = cohort_metric_pack(cohort_row.payload)
            if pack != BAIJIU_PACK:
                raise _HandlerError(
                    f"online peer collection does not support metric pack {pack}; "
                    "no collection was started"
                )
        store = CollectArtifactStore(self.settings.data_dir, job.run_id)
        index = store.load_index()
        if not index:
            index = {
                "schema": COLLECTION_SCHEMA,
                "run_id": job.run_id,
                "payload": payload.model_dump(mode="json"),
                "started_at": datetime.now(UTC).isoformat(),
                "companies": {},
                "frozen_inputs": None,
            }
        elif index.get("schema") != COLLECTION_SCHEMA or index.get("payload") != payload.model_dump(
            mode="json"
        ):
            raise _HandlerError(
                f"run {job.run_id} collect artifacts do not match the claimed payload"
            )

        collector = EastmoneyAnnualCollector(
            self._build_source(store),
            cache=SavedResponseCache(store),
            max_retries=self.settings.peer_collect_retries,
            retry_backoff_seconds=self._retry_backoff_seconds,
            min_interval_seconds=self.settings.peer_collect_min_interval_seconds,
            sleep=self._sleep,
        )
        roster = await self._load_roster(payload)
        if index.get("frozen_inputs") is None:
            index["frozen_inputs"] = await self._frozen_plan(payload, roster)
            store.save_index(index)

        for entry in roster:
            ticker = str(entry["ticker"])
            state = index["companies"].get(ticker)
            if isinstance(state, dict) and state.get("status") in {"collected", "failed"}:
                continue  # checkpoint: finished companies are never re-collected
            log_start = len(collector.request_log)

            async def collect_one(ticker: str = ticker) -> CompanyAnnualCollection:
                return await collector.collect_company_annual(ticker, payload.report_period)

            try:
                collection = await ctx.run_with_heartbeat(job.lease, collect_one)
            except CompanyTypeUnknownError as exc:
                await self._checkpoint_failure(job, index, store, ticker, collector, log_start, exc)
                continue
            except (EastmoneyAnnualError, EastmoneyAnnualDataError) as exc:
                # Explicit schema / data / HTTP refusal: this company fails,
                # the task level never blind-retries it (WP7 owns retries).
                await self._checkpoint_failure(job, index, store, ticker, collector, log_start, exc)
                continue
            except EastmoneyAnnualTransientError:
                # Transient transport failure: archive the attempts, then let
                # the worker's existing limited retry requeue the run.
                self._archive_requests(index, ticker, collector, log_start, status="pending")
                store.save_index(index)
                raise
            await self._save_collection(
                job, index, store, payload=payload, ticker=ticker, entry=entry,
                collection=collection, collector=collector, log_start=log_start,
            )
        return await self._finalize(job, payload, index)

    # -- steps -------------------------------------------------------------- #

    def _build_source(self, store: CollectArtifactStore) -> EastmoneyAnnualSource:
        inner = self._injected_source  # tests inject a fake; production goes HTTP
        if inner is None:
            from investment_agent.providers.eastmoney_annual import HttpEastmoneyAnnualSource

            inner = HttpEastmoneyAnnualSource(
                timeout_seconds=30.0,
            )
        return ArtifactSavingSource(inner, store)

    async def _load_roster(
        self, payload: PeerCollectPayload
    ) -> list[dict[str, Any]]:
        """The payload-bound roster entries (tickers never come from callers)."""

        async with session_scope() as session:
            row = await session.get(PeerCohortSnapshot, payload.cohort_snapshot_id)
            if row is None or row.revision != payload.cohort_revision:
                raise _HandlerError(
                    f"cohort snapshot {payload.cohort_snapshot_id} revision "
                    f"{payload.cohort_revision} does not exist"
                )
            entries = row.payload.get("entries") if isinstance(row.payload, dict) else None
            if not isinstance(entries, list) or not entries:
                raise _HandlerError(f"cohort snapshot {row.id} carries no roster entries")
            return [
                {
                    "company_id": int(entry["company_id"]),
                    "listing_id": int(entry["listing_id"]),
                    "ticker": str(entry["ticker"]),
                    "name": str(entry.get("name") or ""),
                }
                for entry in sorted(entries, key=lambda item: int(item["company_id"]))
            ]

    async def _frozen_plan(
        self, payload: PeerCollectPayload, roster: Sequence[Mapping[str, Any]]
    ) -> dict[str, Any]:
        """The task-start freeze record: each member's pre-existing version.

        Purely informational (the finalize freeze is the binding one) but it
        documents, at task start, which member reuses an older in-scope
        version if this run's collection fails and which starts from a gap.
        """

        plan: dict[str, Any] = {}
        async with session_scope() as session:
            repo = PeerAnnualSnapshotRepository(session)
            for entry in roster:
                row = await self._latest_version(
                    repo,
                    company_id=int(entry["company_id"]),
                    report_period=payload.report_period,
                    provider=payload.provider,
                    adapter_version=payload.adapter_version,
                )
                plan[str(entry["ticker"])] = {
                    "company_id": int(entry["company_id"]),
                    "existing_snapshot_id": row.id if row is not None else None,
                }
        return plan

    @staticmethod
    async def _latest_version(
        repo: PeerAnnualSnapshotRepository,
        *,
        company_id: int,
        report_period: date,
        provider: str,
        adapter_version: str,
    ) -> PeerAnnualSnapshot | None:
        rows = await repo.versions(
            company_id=company_id, report_period=report_period, provider=provider
        )
        rows = [row for row in rows if row.adapter_version == adapter_version]
        if not rows:
            return None
        return max(rows, key=lambda row: (row.captured_at, row.semantic_hash))

    async def _save_collection(
        self,
        job: ClaimedJob,
        index: dict[str, Any],
        store: CollectArtifactStore,
        *,
        payload: PeerCollectPayload,
        ticker: str,
        entry: Mapping[str, Any],
        collection: CompanyAnnualCollection,
        collector: EastmoneyAnnualCollector,
        log_start: int,
    ) -> None:
        """One company's fact write + checkpoint commit (one fenced transaction)."""

        if (
            collection.provider != payload.provider
            or collection.adapter_version != payload.adapter_version
        ):
            raise _HandlerError(
                f"collector returned scope provider={collection.provider} "
                f"adapter={collection.adapter_version}, but the task is bound to "
                f"provider={payload.provider} adapter={payload.adapter_version}"
            )
        fields, proofs = build_snapshot_fields(collection)
        semantic_hash, content_hash = snapshot_hashes(fields, proofs)
        requests = [_dump_request(record) for record in collector.request_log[log_start:]]
        index["companies"][ticker] = {
            "status": "collected",
            "finished_at": datetime.now(UTC).isoformat(),
            "snapshot_id": None,
            "semantic_hash": semantic_hash,
            "snapshot_saved": False,
            "requests": requests,
        }
        async with session_scope() as session:
            repo = PeerAnnualSnapshotRepository(session)
            existing = await repo.by_unique_key(
                company_id=int(entry["company_id"]),
                report_period=collection.report_period,
                provider=collection.provider,
                adapter_version=collection.adapter_version,
                semantic_hash=semantic_hash,
            )
            if existing is not None:
                snapshot_id, saved = existing.id, False
            else:
                row = await repo.add(
                    PeerAnnualSnapshot(
                        id=str(uuid.uuid4()),
                        company_id=int(entry["company_id"]),
                        listing_id=int(entry["listing_id"]),
                        report_period=collection.report_period,
                        provider=collection.provider,
                        adapter_version=collection.adapter_version,
                        captured_at=collection.captured_at,
                        content_hash=content_hash,
                        semantic_hash=semantic_hash,
                        fields={metric: f.model_dump(mode="json") for metric, f in fields.items()},
                        verification=dict(proofs),
                    )
                )
                snapshot_id, saved = row.id, True
            state = index["companies"][ticker]
            state["snapshot_id"] = snapshot_id
            state["snapshot_saved"] = saved
            await PipelineRunRepository(session).record_metadata(
                job.run_id, {"peer_collect": self._metadata_view(index, store)}, lease=job.lease
            )
        # Only after the fact write + checkpoint committed does the index file
        # name the company finished: a crash in between re-collects it, and the
        # saved responses plus the unique key make that replay a no-op.
        store.save_index(index)
        log.info(
            "peer_collect.company_saved",
            run_id=job.run_id,
            ticker=ticker,
            snapshot_saved=saved,
        )

    async def _checkpoint_failure(
        self,
        job: ClaimedJob,
        index: dict[str, Any],
        store: CollectArtifactStore,
        ticker: str,
        collector: EastmoneyAnnualCollector,
        log_start: int,
        exc: Exception,
    ) -> None:
        """One company failed terminally: record the reason, keep the group going."""

        self._archive_requests(index, ticker, collector, log_start, status="failed", reason=exc)
        async with session_scope() as session:
            await PipelineRunRepository(session).record_metadata(
                job.run_id, {"peer_collect": self._metadata_view(index, store)}, lease=job.lease
            )
        store.save_index(index)
        log.warning(
            "peer_collect.company_failed",
            run_id=job.run_id,
            ticker=ticker,
            error=f"{type(exc).__name__}: {exc}",
        )

    def _archive_requests(
        self,
        index: dict[str, Any],
        ticker: str,
        collector: EastmoneyAnnualCollector,
        log_start: int,
        *,
        status: str,
        reason: Exception | None = None,
    ) -> None:
        state = index["companies"].setdefault(
            ticker, {"status": status, "finished_at": datetime.now(UTC).isoformat()}
        )
        state["status"] = status
        state["requests"] = [
            _dump_request(record) for record in collector.request_log[log_start:]
        ]
        if reason is not None:
            state["reason"] = f"{type(reason).__name__}: {reason}"

    @staticmethod
    def _metadata_view(index: Mapping[str, Any], store: CollectArtifactStore) -> dict[str, Any]:
        """The checkpoint summary persisted in the run's ``metadata_json``."""

        companies = index.get("companies", {})
        return {
            "checkpoint": {
                ticker: {
                    "status": state.get("status"),
                    "snapshot_id": state.get("snapshot_id"),
                    "reason": state.get("reason"),
                }
                for ticker, state in sorted(companies.items())
                if isinstance(state, dict)
            },
            "collected": sum(
                1
                for state in companies.values()
                if isinstance(state, dict) and state.get("status") == "collected"
            ),
            "failed": [
                ticker
                for ticker, state in sorted(companies.items())
                if isinstance(state, dict) and state.get("status") == "failed"
            ],
            "artifact_dir": str(store.root),
            "artifact_index": str(store.index_path),
            "responses_index": str(store.responses_index_path),
        }

    # -- batch finalization (the offline submission functions, reused) -------- #

    async def _finalize(
        self, job: ClaimedJob, payload: PeerCollectPayload, index: dict[str, Any]
    ) -> JobOutcome:
        now = datetime.now(UTC)
        store = CollectArtifactStore(self.settings.data_dir, job.run_id)
        async with session_scope() as session:
            cohort_row = await session.get(PeerCohortSnapshot, payload.cohort_snapshot_id)
            if cohort_row is None or cohort_row.revision != payload.cohort_revision:
                raise _HandlerError(
                    f"cohort snapshot {payload.cohort_snapshot_id} revision "
                    f"{payload.cohort_revision} does not exist"
                )
            if cohort_metric_pack(cohort_row.payload) != BAIJIU_PACK:
                raise _HandlerError("online collection cannot finalize a non-baijiu metric pack")
            await reserve_batch_transaction(session)
            # The functions below are the WP6 offline submission pipeline,
            # reused function-for-function: freeze -> materialize -> build+save.
            frozen, missing_companies = await peer_batch._freeze_companies(
                session,
                cohort_row=cohort_row,
                report_period=payload.report_period,
                provider=payload.provider,
                adapter_version=payload.adapter_version,
                snapshot_ids={
                    int(entry["company_id"]): (
                        index["companies"].get(str(entry["ticker"]), {}).get("snapshot_id")
                        or index.get("frozen_inputs", {}).get(str(entry["ticker"]), {}).get("existing_snapshot_id")
                    )
                    for entry in cohort_row.payload["entries"]
                },
            )
            entries = sorted(
                (e for e in cohort_row.payload["entries"]),
                key=lambda item: int(item["company_id"]),
            )
            target_gaps: list[TargetGap] = []
            buildable = []
            for entry in entries:
                company_id = int(entry["company_id"])
                if company_id in frozen:
                    buildable.append(entry)
                    continue
                state = index["companies"].get(str(entry["ticker"]))
                reason = (
                    f"collection failed: {state['reason']}"
                    if isinstance(state, dict) and state.get("reason")
                    else "no annual input was collected for this batch"
                )
                target_gaps.append(
                    TargetGap(company_id=company_id, ticker=str(entry["ticker"]), reason=reason)
                )

            evidence_refs = await peer_batch._materialize_evidence(
                session, owner_id=self._owner_id(), frozen=frozen
            )
            batch_run_id = str(job.run_id)
            results: list[TargetCalculationRefs] = [
                await save_peer_calculations(
                    session,
                    owner_id=self._owner_id(),
                    batch=peer_batch._frozen_batch(
                        cohort_row=cohort_row,
                        report_period=payload.report_period,
                        frozen=frozen,
                        target_company_id=int(entry["company_id"]),
                    ),
                    evidence_refs=evidence_refs,
                    as_of=now,
                    batch_run_id=batch_run_id,
                    # Online facts carry disclosure dates and materialize; a
                    # field that still lacks any date basis is declared (never
                    # hidden), exactly as in the WP6 offline submission.
                    require_fact_refs=False,
                )
                for entry in buildable
            ]

            scan = await scan_committed_batch_mappings(session, self.settings.data_dir)
            scope = mappings_in_scope(
                scan.valid,
                cohort_ref=payload.cohort_ref(),
                report_period=payload.report_period,
                provider=payload.provider,
                adapter_version=payload.adapter_version,
            )
            draft = peer_batch._mapping_from_results(
                batch_run_id=batch_run_id,
                cohort_row=cohort_row,
                report_period=payload.report_period,
                provider=payload.provider,
                adapter_version=payload.adapter_version,
                # Keep the admission generation: a late old run stays old.
                generation=payload.generation,
                submitted_at=now,
                results=results,
                frozen=frozen,
                missing_companies=missing_companies,
                target_gaps=target_gaps,
                evidence_refs=evidence_refs,
            )
            existing = find_identical_submission(scope, targets_signature(draft))
            if existing is not None:
                mapping, created = existing, False
            else:
                await register_batch_commit(session, draft)
                write_batch_mapping(self.settings.data_dir, draft)
                mapping, created = draft, True

            metadata: dict[str, object] = {
                "peer_collect": {
                    **self._metadata_view(index, store),
                    "mapping": {
                        "batch_run_id": mapping.batch_run_id,
                        "generation": mapping.generation,
                        "status": mapping.status,
                        "created": created,
                        "content_hash": mapping.content_hash,
                        "artifact": str(mapping_artifact_path(self.settings.data_dir, mapping.batch_run_id)),
                        "targets": len(mapping.targets),
                        "missing_companies": [
                            item.ticker for item in mapping.manifest.missing_companies
                        ],
                        "target_gaps": [gap.ticker for gap in mapping.manifest.target_gaps],
                    },
                }
            }
            if mapping.status == "success":
                await PipelineRunRepository(session).mark_success(
                    job.run_id, metadata, lease=job.lease
                )
                outcome: JobOutcome = "completed"
                summary = f"batch {mapping.batch_run_id} generation {mapping.generation} success"
            else:
                summary = self._partial_summary(index, mapping)
                await PipelineRunRepository(session).mark_partial(
                    job.run_id, summary, metadata, lease=job.lease
                )
                outcome = "partial"
        store.save_index(index)
        log.info(
            "peer_collect.finalized",
            run_id=job.run_id,
            batch_run_id=mapping.batch_run_id,
            status=mapping.status,
            created=created,
        )
        return outcome

    @staticmethod
    def _owner_id() -> OwnerId:
        return "local_owner"

    @staticmethod
    def _partial_summary(index: Mapping[str, Any], mapping: PeerBatchMapping) -> str:
        failed = [
            f"{ticker} ({state.get('reason')})"
            for ticker, state in sorted(index.get("companies", {}).items())
            if isinstance(state, dict) and state.get("status") == "failed"
        ]
        return (
            f"batch {mapping.batch_run_id} generation {mapping.generation} partial; "
            f"failed companies: {', '.join(failed) if failed else 'none recorded'}"
        )


# --------------------------------------------------------------------------- #
# Admission check (research submission path + ``peers admit`` command)
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class PeerCollectAdmission:
    """One admission decision; ``gaps`` always carries the original gaps."""

    outcome: Literal["not_needed", "no_roster", "no_period", "enqueued", "reused", "pending", "cooldown"]
    ticker: str
    report_period: date | None
    gaps: tuple[str, ...] = ()
    run_id: int | None = None
    generation: int | None = None
    batch_run_id: str | None = None
    detail: str = ""


async def admit_peer_collect(
    session: AsyncSession,
    *,
    ticker: str,
    data_dir: Path,
    cooldown_seconds: float,
    provider: str = PROVIDER,
    adapter_version: str = ADAPTER_VERSION,
    now: datetime | None = None,
    triggered_by: str = "admission",
) -> PeerCollectAdmission:
    """Coverage admission for one target (read-only until it enqueues).

    The current read (:mod:`investment_agent.industry_peers.service`, never an
    upstream call) decides: outside the roster -> ``no_roster``; covered ->
    ``not_needed``; a queued/running collect run of the scope -> ``pending``;
    a known correction or update (stale) enqueues immediately; any other gap
    (first miss, partial coverage) enqueues only when the last check of the
    scope is older than ``cooldown_seconds`` - inside the window the original
    gaps are returned unchanged (``cooldown``). GET endpoints and the agent
    never call this.
    """

    from investment_agent.industry_peers.contracts import PeerContextStatus
    from investment_agent.industry_peers.service import get_industry_peer_context

    at = now or datetime.now(UTC)
    if at.tzinfo is None:
        raise ValueError("now must be timezone-aware")
    result = await get_industry_peer_context(
        session,
        ticker=ticker,
        data_dir=data_dir,
        provider=provider,
        adapter_version=adapter_version,
    )
    ticker_label = result.target.ticker
    if result.status is PeerContextStatus.NOT_SUPPORTED:
        return PeerCollectAdmission(
            outcome="no_roster", ticker=ticker_label, report_period=None,
            gaps=result.gaps, detail=result.gaps[0] if result.gaps else "",
        )
    period = result.current_report_period
    if period is None:
        return PeerCollectAdmission(
            outcome="no_period", ticker=ticker_label, report_period=None,
            gaps=result.gaps,
            detail="cannot determine the target year from local disclosure records",
        )

    if result.cohort_ref is None:
        return PeerCollectAdmission(
            outcome="no_roster", ticker=ticker_label, report_period=period,
            gaps=result.gaps, detail="no cohort roster resolved for the target",
        )
    from investment_agent.storage.repositories.peer import PeerCohortSnapshotRepository

    cohort_row = await PeerCohortSnapshotRepository(session).get(str(result.cohort_ref.id))
    if cohort_row is None:
        return PeerCollectAdmission(
            outcome="no_roster", ticker=ticker_label, report_period=period,
            gaps=result.gaps, detail="the resolved cohort roster no longer exists",
        )

    active = await find_active_scope_run(
        session,
        cohort=cohort_row,
        report_period=period,
        provider=provider,
        adapter_version=adapter_version,
    )
    if active is not None:
        return PeerCollectAdmission(
            outcome="pending", ticker=ticker_label, report_period=period,
            run_id=active.id, gaps=result.gaps,
            detail=f"collect run {active.id} is {active.status}",
        )

    stale = result.status is PeerContextStatus.STALE
    covered = (
        result.status is PeerContextStatus.READY
        and result.old_reference is False
        and result.batch_status == "success"
    )
    if result.status is PeerContextStatus.CONFLICT:
        covered = True  # conflicts need a correction basis, not a re-collection
    if covered and not stale:
        return PeerCollectAdmission(
            outcome="not_needed", ticker=ticker_label, report_period=period,
            batch_run_id=result.batch_run_id, gaps=result.gaps,
            detail=f"batch {result.batch_run_id} covers the target",
        )

    # The original gaps: what the read could not answer for the target plus
    # the submitted batch's own coverage gaps (missing companies, targets
    # that could not be built) - the cooldown returns exactly these.
    gaps = list(result.gaps)
    scan = await scan_committed_batch_mappings(session, data_dir)
    mapping = select_current_mapping(
        mappings_in_scope(
            scan.valid,
            cohort_ref=ObjectRef(
                kind="peer_cohort_snapshot",
                id=uuid.UUID(cohort_row.id),
                revision=cohort_row.revision,
            ),
            report_period=period,
            provider=provider,
            adapter_version=adapter_version,
        )
    )
    if mapping is not None:
        for item in mapping.manifest.missing_companies:
            gaps.append(f"{item.ticker}: {item.reason}")
        for gap in mapping.manifest.target_gaps:
            gaps.append(f"{gap.ticker}: {gap.reason}")
    if not gaps:
        gaps.append("the submitted batch does not fully cover the roster")

    if not stale:
        # Cooldown: repeated gaps or failures inside the window after the last
        # check return the original gaps instead of re-collecting.
        last_check = await _last_scope_check(
            session,
            cohort=cohort_row,
            report_period=period,
            provider=provider,
            adapter_version=adapter_version,
            data_dir=data_dir,
        )
        if last_check is not None and (at - last_check).total_seconds() < cooldown_seconds:
            return PeerCollectAdmission(
                outcome="cooldown", ticker=ticker_label, report_period=period,
                gaps=tuple(gaps), batch_run_id=result.batch_run_id,
                detail=(
                    f"last scope check {last_check.isoformat()} is inside the "
                    f"{cooldown_seconds:.0f}s cooldown; returning the original gaps"
                ),
            )

    enqueued = await enqueue_peer_collect(
        session,
        report_period=period,
        mode="refresh" if stale else "full",
        triggered_by=triggered_by,
        data_dir=data_dir,
        cohort_row=cohort_row,
        provider=provider,
        adapter_version=adapter_version,
    )
    return PeerCollectAdmission(
        outcome="enqueued" if enqueued.created else "reused",
        ticker=ticker_label,
        report_period=period,
        gaps=tuple(gaps),
        run_id=enqueued.run.id,
        generation=enqueued.generation,
        detail=(
            "stale results bypass the cooldown"
            if stale
            else "gap admitted for collection"
        ),
    )


async def _last_scope_check(
    session: AsyncSession,
    *,
    cohort: PeerCohortSnapshot,
    report_period: date,
    provider: str,
    adapter_version: str,
    data_dir: Path,
) -> datetime | None:
    """The newest check evidence of the scope: the submitted mapping's
    ``submitted_at`` or any prior run's terminal/creation time."""

    times: list[datetime] = []
    scan = await scan_committed_batch_mappings(session, data_dir)
    mapping = select_current_mapping(
        mappings_in_scope(
            scan.valid,
            cohort_ref=ObjectRef(
                kind="peer_cohort_snapshot",
                id=uuid.UUID(cohort.id),
                revision=cohort.revision,
            ),
            report_period=report_period,
            provider=provider,
            adapter_version=adapter_version,
        )
    )
    if mapping is not None:
        times.append(mapping.submitted_at)
    for run in await _runs_in_scope(
        session,
        cohort=cohort,
        report_period=report_period,
        provider=provider,
        adapter_version=adapter_version,
    ):
        moment = run.finished_at or run.started_at
        if moment is not None:
            times.append(moment if moment.tzinfo is not None else moment.replace(tzinfo=UTC))
    return max(times) if times else None


