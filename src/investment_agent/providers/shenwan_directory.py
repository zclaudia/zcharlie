"""Shenwan 2021 (申万 2021) industry code directory: code -> name, level, parent.

The Shenwan classification history (:mod:`investment_agent.providers.akshare_shenwan`)
carries 6-digit industry codes only. The digits encode the hierarchy:
``340501`` is level 3, its level-2 parent is ``340500`` and its level-1
parent ``340000``. Names come from a versioned directory file,
``config/shenwan_2021.yaml``, generated by ``tools/refresh_shenwan_directory.py``
(Shenwan's official code table) and committed; runtime
code only reads the file. Codes missing from it (legacy pre-2021 codes,
industries without current constituents) keep their code and are logged by
the callers.

Era rule: Shenwan published the 2021 standard on 2021-07-30
(:data:`SW2021_CUTOVER`). An interval of the history that *ended* on or
before that day carries a pre-2021 (SW 2014 or older) code whose meaning may
differ from the same digits in the 2021 directory, so it is never named or
grouped through the directory (:func:`is_sw2021_interval`).

Pure module: no network, no akshare import.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import date
from functools import lru_cache
from pathlib import Path

import yaml

SW2021_SYSTEM = "sw2021"
SW2021_CUTOVER = date(2021, 7, 30)
"""First day of the Shenwan 2021 standard."""

DEFAULT_SHENWAN_DIRECTORY_PATH = (
    Path(__file__).resolve().parents[3] / "config" / "shenwan_2021.yaml"
)

_LEVELS = (1, 2, 3)


def is_sw_code(code: str | None) -> bool:
    return code is not None and len(code) == 6 and code.isdigit()


def level_codes(code: str) -> tuple[str, str, str]:
    """``340501`` -> ``("340000", "340500", "340501")``."""

    if not is_sw_code(code):
        raise ValueError(f"not a 6-digit Shenwan industry code: {code!r}")
    return f"{code[:2]}0000", f"{code[:4]}00", code


def code_level(code: str) -> int:
    """Level implied by the trailing zeros (``340000`` -> 1, ``340500`` -> 2)."""

    l1, l2, _ = level_codes(code)
    if code == l1:
        return 1
    if code == l2:
        return 2
    return 3


def is_sw2021_interval(valid_from: date, valid_to: date | None) -> bool:
    """True when the interval reaches the 2021 standard (see module docstring)."""

    del valid_from  # an interval starting before the cutover may continue into it
    return valid_to is None or valid_to > SW2021_CUTOVER


@dataclass(frozen=True)
class ShenwanIndustry:
    code: str
    name: str
    level: int
    parent: str | None = None
    index_code: str | None = None
    """Shenwan index tracking the industry (``801010.SI``), informational."""


@dataclass(frozen=True)
class DirectoryDiff:
    added: tuple[str, ...]
    removed: tuple[str, ...]
    renamed: tuple[tuple[str, str, str], ...]
    """``(code, old name, new name)``."""

    @property
    def changed(self) -> bool:
        return bool(self.added or self.removed or self.renamed)


@dataclass(frozen=True)
class ShenwanDirectory:
    version: str
    industries: Mapping[str, ShenwanIndustry]
    captured_on: date | None = None
    source: str = ""
    unresolved_index_codes: tuple[str, ...] = field(default=())
    """Level-3 indexes whose code could not be reverse-looked-up (no members)."""

    def get(self, code: str | None) -> ShenwanIndustry | None:
        if code is None:
            return None
        return self.industries.get(code)

    def name_of(self, code: str | None) -> str | None:
        industry = self.get(code)
        return industry.name if industry else None

    def chain(self, code: str) -> tuple[ShenwanIndustry, ...]:
        """Level 1 .. the code's own level; only entries present in the directory."""

        if not is_sw_code(code):
            return ()
        found = []
        for candidate in dict.fromkeys(level_codes(code)):
            industry = self.industries.get(candidate)
            if industry is not None and industry.level <= code_level(code):
                found.append(industry)
        return tuple(found)

    def codes(self, level: int) -> list[str]:
        return sorted(code for code, item in self.industries.items() if item.level == level)

    def diff(self, newer: ShenwanDirectory) -> DirectoryDiff:
        old, new = self.industries, newer.industries
        return DirectoryDiff(
            added=tuple(sorted(set(new) - set(old))),
            removed=tuple(sorted(set(old) - set(new))),
            renamed=tuple(
                (code, old[code].name, new[code].name)
                for code in sorted(set(old) & set(new))
                if old[code].name != new[code].name
            ),
        )


def build_directory(
    industries: Iterable[ShenwanIndustry],
    *,
    version: str,
    captured_on: date | None = None,
    source: str = "",
    unresolved_index_codes: Iterable[str] = (),
) -> ShenwanDirectory:
    entries: dict[str, ShenwanIndustry] = {}
    for industry in industries:
        _validate(industry)
        if industry.code in entries and entries[industry.code] != industry:
            raise ValueError(f"conflicting directory entries for {industry.code}")
        entries[industry.code] = industry
    for industry in entries.values():
        if industry.parent is not None and industry.parent not in entries:
            raise ValueError(f"{industry.code}: parent {industry.parent} missing")
    return ShenwanDirectory(
        version=version,
        industries=dict(sorted(entries.items())),
        captured_on=captured_on,
        source=source,
        unresolved_index_codes=tuple(sorted(set(unresolved_index_codes))),
    )


def _validate(industry: ShenwanIndustry) -> None:
    if not is_sw_code(industry.code):
        raise ValueError(f"invalid Shenwan code {industry.code!r}")
    if industry.level not in _LEVELS or code_level(industry.code) != industry.level:
        raise ValueError(f"{industry.code}: level {industry.level} does not match the code")
    if not industry.name.strip():
        raise ValueError(f"{industry.code}: empty name")
    expected_parent = None
    if industry.level >= 2:
        l1, l2, _ = level_codes(industry.code)
        expected_parent = l1 if industry.level == 2 else l2
    if industry.parent != expected_parent:
        raise ValueError(
            f"{industry.code}: parent {industry.parent!r}, expected {expected_parent!r}"
        )


