def parse_shenwan_directory(raw: object) -> ShenwanDirectory:
    if not isinstance(raw, dict):
        raise ValueError("Shenwan directory must be a mapping")
    version = str(raw.get("version") or "").strip()
    if not version:
        raise ValueError("Shenwan directory needs a version")
    if str(raw.get("system") or SW2021_SYSTEM) != SW2021_SYSTEM:
        raise ValueError(f"Shenwan directory system must be {SW2021_SYSTEM!r}")
    items = raw.get("industries")
    if not isinstance(items, dict) or not items:
        raise ValueError("Shenwan directory needs industries")
    industries = []
    for code, entry in items.items():
        if not isinstance(entry, dict):
            raise ValueError(f"invalid directory entry for {code!r}")
        parent = entry.get("parent")
        industries.append(
            ShenwanIndustry(
                code=str(code),
                name=str(entry.get("name") or ""),
                level=int(entry.get("level") or 0),
                parent=str(parent) if parent is not None else None,
                index_code=str(entry["index"]) if entry.get("index") else None,
            )
        )
    captured = raw.get("captured_on")
    return build_directory(
        industries,
        version=version,
        captured_on=date.fromisoformat(str(captured)) if captured else None,
        source=str(raw.get("source") or ""),
        unresolved_index_codes=[str(code) for code in raw.get("unresolved_index_codes") or []],
    )


def load_shenwan_directory(path: Path | str | None = None) -> ShenwanDirectory:
    target = Path(path) if path is not None else DEFAULT_SHENWAN_DIRECTORY_PATH
    return parse_shenwan_directory(yaml.safe_load(target.read_text(encoding="utf-8")))


@lru_cache(maxsize=1)
def default_shenwan_directory() -> ShenwanDirectory:
    return load_shenwan_directory()


_HEADER = """\
# Shenwan 2021 (申万 2021) industry directory: 6-digit code -> name, level, parent.
#
# GENERATED by tools/refresh_shenwan_directory.py - do not edit by hand.
# Source: Shenwan's official code table SwClassCode_2021.xls (swsresearch.com);
# the tool can cross-check it against legulegu's level-3 constituents
# (AkShare sw_index_third_cons). Codes not listed here (pre-2021 codes of
# stocks delisted before the 2021 standard) are stored with their code as the
# name and fall back to CSRC for industry groups.
"""


def dump_shenwan_directory(directory: ShenwanDirectory) -> str:
    """Stable, diff-friendly YAML (one flow mapping per code)."""

    lines = [_HEADER.rstrip("\n")]
    lines.append(f'version: "{directory.version}"')
    lines.append(f"system: {SW2021_SYSTEM}")
    if directory.source:
        lines.append(f"source: {_quote(directory.source)}")
    if directory.captured_on:
        lines.append(f"captured_on: {directory.captured_on.isoformat()}")
    for level in _LEVELS:
        lines.append(f"# level {level}: {len(directory.codes(level))} codes")
    lines.append("industries:")
    for code, item in directory.industries.items():
        parts = [f"name: {_quote(item.name)}", f"level: {item.level}"]
        if item.parent:
            parts.append(f'parent: "{item.parent}"')
        if item.index_code:
            parts.append(f"index: {item.index_code}")
        lines.append(f'  "{code}": {{{", ".join(parts)}}}')
    if directory.unresolved_index_codes:
        lines.append("unresolved_index_codes:")
        lines.extend(f"  - {code}" for code in directory.unresolved_index_codes)
    else:
        lines.append("unresolved_index_codes: []")
    return "\n".join(lines) + "\n"


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
